# Helper function to replace an object in text by player ID
def replace_player_block(text, pid, new_block):
    pat = r'\{\s*id:\s*["\']' + pid + r'["\'][\s\S]*?\n  \},?'
    # check if matched
    if not re.search(pat, text):
        print(f"WARNING: ID {pid} not found!")
    return re.sub(pat, new_block, text)

